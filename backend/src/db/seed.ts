async function main() {
  console.log('Seeding obligations référentielles...');

  for (const ob of obligations) {
    await prisma.obligationRef.upsert({
      where: { code: ob.code },
      update: ob,
      create: ob,
    });
  }

  console.log(`✅ ${obligations.length} obligations insérées/mises à jour`);
}

main()
  .catch(console.error)
  .finally(() => prisma.$disconnect());
